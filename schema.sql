-- profiles
CREATE POLICY "Public profiles are viewable by everyone"
ON public.profiles
FOR SELECT
USING (true);

CREATE POLICY "Users can insert their own profile"
ON public.profiles
FOR INSERT
WITH CHECK (auth.uid() = id);

CREATE POLICY "Users can update their own profile"
ON public.profiles
FOR UPDATE
USING (auth.uid() = id)
WITH CHECK (auth.uid() = id);

-- loads
CREATE POLICY "Public loads are viewable by everyone"
ON public.loads
FOR SELECT
USING (true);

CREATE POLICY "Employers can insert loads"
ON public.loads
FOR INSERT
WITH CHECK (auth.uid() = employer_id);

CREATE POLICY "Employers can update own loads"
ON public.loads
FOR UPDATE
USING (auth.uid() = employer_id)
WITH CHECK (auth.uid() = employer_id);

CREATE POLICY "Employers can delete own loads"
ON public.loads
FOR DELETE
USING (auth.uid() = employer_id);

-- bids
CREATE POLICY "Drivers can insert own bids"
ON public.bids
FOR INSERT
WITH CHECK (auth.uid() = driver_id);

CREATE POLICY "Drivers can see own bids or bids on their loads"
ON public.bids
FOR SELECT
USING (
  auth.uid() = driver_id OR
  EXISTS (
    SELECT 1
    FROM public.loads l
    WHERE l.id = bids.load_id
      AND l.employer_id = auth.uid()
  )
);

CREATE POLICY "Employers can respond bids on own loads"
ON public.bids
FOR UPDATE
USING (
  EXISTS (
    SELECT 1
    FROM public.loads l
    WHERE l.id = bids.load_id
      AND l.employer_id = auth.uid()
  )
)
WITH CHECK (
  EXISTS (
    SELECT 1
    FROM public.loads l
    WHERE l.id = bids.load_id
      AND l.employer_id = auth.uid()
  )
);

-- notifications
CREATE POLICY "Users can create notifications as themselves"
ON public.notifications
