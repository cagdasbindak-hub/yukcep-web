-- YUKCEP DB SCHEMA (Supabase / Postgres)
-- This schema matches the current frontend contract in src/App.jsx and src/components/AuthScreen.jsx.

-- USERS (Supabase Auth ile senkronize)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT UNIQUE NOT NULL,
  full_name TEXT,
  phone TEXT,
  role TEXT NOT NULL DEFAULT 'driver' CHECK (role IN ('driver', 'employer', 'admin')),
  rating NUMERIC(2,1) DEFAULT 5.0 CHECK (rating >= 0 AND rating <= 5),
  avatar_url TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- LOADS (Yuk Ilanlari)
CREATE TABLE IF NOT EXISTS public.loads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employer_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  origin_city TEXT NOT NULL,
  destination_city TEXT NOT NULL,
  distance_km INTEGER,
  load_type TEXT NOT NULL,
  trailer_type TEXT CHECK (trailer_type IN ('Kapalı', 'Açık', 'Frigorifik', 'Damperli')),
  weight_kg INTEGER,
  price NUMERIC(12,2),
  currency TEXT NOT NULL DEFAULT 'TRY',
  kdv_included BOOLEAN NOT NULL DEFAULT true,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'assigned', 'completed', 'cancelled')),
  pickup_date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  is_urgent BOOLEAN NOT NULL DEFAULT false,
  is_fleet BOOLEAN NOT NULL DEFAULT false,
  truck_count INTEGER NOT NULL DEFAULT 1 CHECK (truck_count > 0)
);

-- BIDS (Teklifler)
CREATE TABLE IF NOT EXISTS public.bids (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  load_id BIGINT NOT NULL REFERENCES public.loads(id) ON DELETE CASCADE,
  driver_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  price NUMERIC(12,2) NOT NULL CHECK (price > 0),
  status TEXT NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE(load_id, driver_id)
);

-- NOTIFICATIONS
CREATE TABLE IF NOT EXISTS public.notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  actor_id UUID NOT NULL DEFAULT auth.uid() REFERENCES public.profiles(id) ON DELETE CASCADE,
  message TEXT NOT NULL,
  is_read BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- RUNTIME LOGS (istemci hata/olay izleme)
CREATE TABLE IF NOT EXISTS public.runtime_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_event_at TIMESTAMPTZ,
  level TEXT NOT NULL CHECK (level IN ('info', 'warn', 'error')),
  event_code TEXT NOT NULL,
  details TEXT,
  session_id TEXT NOT NULL,
  user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  screen TEXT,
  app_version TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

